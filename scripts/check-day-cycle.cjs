const assert = require('node:assert/strict')
const THREE = require('three')
const { sourceModule, loadGeometry } = require('./island-geometry.cjs')
const { createDayCycle, DAY_HORIZON, DUSK_HORIZON } = sourceModule('day-cycle')
const { createIslandSky, createCloudBanks } = sourceModule('island-sky')
const { createIslandWater } = sourceModule('island-water')
const cycle = createDayCycle(), sky = createIslandSky(), water = createIslandWater(loadGeometry())
const frame = (count, reduced = false, paused = false) => {
  for (let i = 0; i < count; i++) {
    cycle.update(1 / 60, reduced, paused)
    sky.setPalette(cycle.value); water.setPalette(cycle.value)
  }
}
const dayWater = water.material.uniforms.uDeep.value.clone()
cycle.setTarget(true, false)
assert.equal(cycle.value, 0, 'toggle must not snap')
frame(60)
assert.ok(Math.abs(cycle.value - .5) < 1e-6, 'halfway after one second')
const halfway = new THREE.Color().lerpColors(DAY_HORIZON, DUSK_HORIZON, .5)
for (const channel of ['r', 'g', 'b']) assert.ok(Math.abs(cycle.horizon[channel] - halfway[channel]) < 1e-6)
assert.ok(sky.night.value > 0 && sky.night.value < 1, 'moon and stars fade with the sky')
assert.equal(water.dusk.value, cycle.value, 'water and caustics share the transition')
assert.ok(sky.material.uniforms.uHorizon.value.equals(cycle.horizon), 'sky meets fog throughout the transition')
const current = cycle.value
frame(90, false, true); assert.equal(cycle.value, current, 'reader/background pause')
cycle.setTarget(false, false); assert.equal(cycle.value, current, 'reversal starts at the current colour')
frame(61); assert.equal(cycle.value, 0); assert.ok(water.material.uniforms.uDeep.value.equals(dayWater))
cycle.setTarget(true, false); frame(121)
assert.equal(cycle.value, 1, 'full transition completes in two seconds')
assert.equal(sky.night.value, 1)
const nightWater = water.material.uniforms.uDeep.value.clone()
water.setPalette(.5)
const expected = new THREE.Color().lerpColors(dayWater, nightWater, .5)
assert.ok(water.material.uniforms.uDeep.value.equals(expected), 'linear colour blend at midpoint')
cycle.setTarget(false, false); frame(30)
cycle.setTarget(false, true); assert.equal(cycle.value, 0, 'enabling Still during a transition settles immediately')
cycle.setTarget(true, true); assert.equal(cycle.value, 1, 'reduced-motion toggle is immediate')
cycle.setTarget(false, false)
cycle.update(60, false, false); assert.ok(cycle.value > .99, 'resume is clamped')
const valid = cycle.value
cycle.update(NaN, false, false); cycle.update(-10, false, false); assert.equal(cycle.value, valid)

const clouds = createCloudBanks()
const initial = clouds.meshes.map(mesh => mesh.instanceMatrix.array.slice())
const arrays = clouds.meshes.map(mesh => mesh.instanceMatrix.array)
clouds.update(20, new THREE.Color('#abcdee'))
assert.equal(clouds.meshes.length, 3, 'three joined cloud shapes')
clouds.meshes.forEach((mesh, index) => {
  assert.notDeepEqual(mesh.instanceMatrix.array, initial[index], 'clouds drift')
  assert.equal(mesh.count, 2)
  assert.equal(mesh.castShadow, false)
  assert.equal(mesh.material.transparent, false, 'joined clouds need no alpha sorting')
  assert.equal(mesh.material.depthWrite, true, 'front surface hides the back surface')
  assert.equal(mesh.material.flatShading, false, 'smooth normals avoid rock-like facets')
})
const frozen = clouds.meshes.map(mesh => mesh.instanceMatrix.array.slice())
const versions = clouds.meshes.map(mesh => mesh.instanceMatrix.version)
clouds.update(20, new THREE.Color('#baceee'))
clouds.meshes.forEach((mesh, index) => {
  assert.deepEqual(mesh.instanceMatrix.array, frozen[index], 'frozen clock freezes clouds')
  assert.equal(mesh.instanceMatrix.array, arrays[index], 'reuse instance storage')
  assert.equal(mesh.instanceMatrix.version, versions[index], 'Still avoids redundant GPU uploads')
  assert.ok(mesh.material.color.equals(new THREE.Color('#baceee')), 'frozen clouds still blend day/dusk palette')
})
assert.equal(sky.starMaterial.uniforms.uNight, sky.moonMaterial.uniforms.uNight)
assert.equal(sky.stars.attributes.position.count, 170)
for (let i = 0; i < 170; i++) assert.ok(sky.stars.attributes.position.getY(i) > 0)
clouds.dispose(); sky.dispose(); water.dispose()
console.log('Day cycle passed: 2-second blend, reversal, pause/resume, instant reduced motion, synchronized fog/sky/water, fading celestial lights and instanced cloud drift.')
