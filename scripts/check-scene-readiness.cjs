const assert = require('node:assert/strict')
const { sourceModule } = require('./island-geometry.cjs')
const { createSceneReadiness } = sourceModule('scene-readiness')

const gate = createSceneReadiness()
const first = gate.begin()
for (let frame = 0; frame < 12; frame++) assert.equal(gate.frame(first), false, 'assets alone cannot reveal an uncompiled scene')
assert.equal(gate.compiled(first), true)
assert.equal(gate.frame(first), false, 'first render warms shadow textures and render targets')
assert.equal(gate.frame(first), false, 'second render warms postprocessing passes')
assert.equal(gate.frame(first), true, 'reveal after the final prepared frame has been presented')
assert.equal(gate.frame(first), false, 'readiness only emits once')

const stale = gate.begin()
gate.cancel(stale)
assert.equal(gate.compiled(stale), false, 'cancelled async compilation cannot reveal the loader')
assert.equal(gate.current(stale), false, 'cancelled animation-frame callbacks are stale')
const replacement = gate.begin()
assert.equal(gate.frame(stale), false)
assert.equal(gate.compiled(replacement), true)
assert.equal(gate.frame(replacement), false)
gate.cancel(stale)
assert.equal(gate.frame(replacement), false, 'old Strict Mode cleanup cannot cancel the replacement')
assert.equal(gate.frame(replacement), true)
assert.equal(gate.current(replacement), true)

console.log('Scene readiness waits for compilation and rendered frames; stale, cancelled, and duplicate reveals are blocked.')
